#!/usr/bin/env python3
#
# frank-sdk — inventory of the board, driver and platform files that the
# FRANK firmware repos carry as copies of one another.
#
# Every copy is hashed twice: as it is, and with its leading comment block
# and whitespace stripped, so a copy that differs only in its licence header
# counts as the same code. Copies are grouped by their path inside the
# driver tree (drivers/hdmi/x.c, common/link/x.c and src/platform/x.c all
# become hdmi/x.c, link/x.c, platform/x.c), and each variant lists the repos
# that hold it and when each repo last changed that file.
#
# Usage: tools/inventory.py [--root DIR-WITH-THE-FIRMWARE-REPOS] [-o docs/inventory.md]
#
# Copyright (c) 2026 Mikhail Matveev <xtreme@rh1.tech>
# SPDX-License-Identifier: MIT

import argparse
import hashlib
import os
import re
import subprocess
import sys
from collections import defaultdict

# the firmware repos with shared drivers; the order is the tie-break when
# two variants are equally recent
REPOS = [
    "frank-dos", "frank-react", "frank-diablo", "frank-war2", "frank-war1",
    "frank-castle", "frank-quake2", "frank-ecat", "frank-carmageddon",
    "frank-blood", "frank-amiga", "frank-duke3d", "frank-shadowwarrior",
    "murm386", "murmheretic", "frank-msx", "frank-wolf", "frank-xt8086",
    "frank-dino",
]

# where the shared code sits in each layout, and the prefix it gets
TREES = [
    ("boards", "boards"),
    ("drivers", ""),
    ("common/boards", "boards"),
    ("common/link", "link"),
    ("common/platform", "platform"),
    ("master/drivers", ""),
    ("platform", "platform"),
    ("src/platform", "platform"),
]
TOP_FILES = ["build.sh", "flash.sh", "release.sh", "swd_flash.sh",
             "pico_sdk_import.cmake"]
EXTS = {".c", ".h", ".cpp", ".hpp", ".pio", ".S", ".s", ".ld", ".cmake",
        ".txt", ".sh", ".py"}
SKIP_DIRS = {"build", "__pycache__", ".git", "stub"}


def norm(data: bytes) -> bytes:
    """the code without its leading comment block and with whitespace runs folded"""
    t = data.decode("utf-8", "replace")
    t = re.sub(r"\A\s*(/\*.*?\*/\s*|(//[^\n]*\n\s*)+|(#[^\n]*\n\s*)+)", "", t,
               count=1, flags=re.S)
    t = re.sub(r"\s+", " ", t).strip()
    return t.encode()


def last_change(repo_dir, rel):
    try:
        out = subprocess.run(["git", "-C", repo_dir, "log", "-1", "--format=%cs", "--", rel],
                             capture_output=True, text=True, timeout=10).stdout.strip()
    except Exception:
        out = ""
    if not out:  # untracked or no git: the file's mtime
        import datetime
        out = datetime.date.fromtimestamp(os.path.getmtime(os.path.join(repo_dir, rel))).isoformat()
    return out


def collect(root):
    groups = defaultdict(list)  # key -> [(repo, rel, raw_md5, norm_md5, lines, date)]
    for repo in REPOS:
        rdir = os.path.join(root, repo)
        if not os.path.isdir(rdir):
            continue
        files = []
        for tree, prefix in TREES:
            tdir = os.path.join(rdir, tree)
            if not os.path.isdir(tdir):
                continue
            for dp, dns, fns in os.walk(tdir):
                dns[:] = [d for d in dns if d not in SKIP_DIRS]
                for fn in fns:
                    if os.path.splitext(fn)[1] not in EXTS:
                        continue
                    full = os.path.join(dp, fn)
                    sub = os.path.relpath(full, tdir)
                    key = os.path.join(prefix, sub) if prefix else sub
                    files.append((key, os.path.relpath(full, rdir)))
        for fn in TOP_FILES:
            if os.path.isfile(os.path.join(rdir, fn)):
                files.append(("top/" + fn, fn))
        for key, rel in files:
            with open(os.path.join(rdir, rel), "rb") as f:
                data = f.read()
            groups[key].append((repo, rel, hashlib.md5(data).hexdigest()[:8],
                                hashlib.md5(norm(data)).hexdigest()[:8],
                                data.count(b"\n"), last_change(rdir, rel)))
    return groups


def report(groups, out):
    shared = {k: v for k, v in groups.items() if len({r for r, *_ in v}) > 1}
    w = out.write
    w("# Inventory of shared files\n\n")
    w("Generated by `tools/inventory.py`; do not edit. Files held by two or more repos,\n")
    w("grouped by their path inside the driver tree. A variant is one distinct code\n")
    w("hash (licence header and whitespace ignored). **newest** = the variant whose\n")
    w("latest change is the most recent: the starting point for the canonical copy.\n\n")
    drift = sorted(shared.items(), key=lambda kv: (-len({x[3] for x in kv[1]}), kv[0]))
    w("| file | repos | variants |\n|---|---:|---:|\n")
    for key, v in drift:
        w(f"| `{key}` | {len(v)} | {len({x[3] for x in v})} |\n")
    w("\n")
    for key, v in drift:
        variants = defaultdict(list)
        for x in v:
            variants[x[3]].append(x)
        if len(variants) == 1:
            continue
        newest = max(variants, key=lambda h: (max(x[5] for x in variants[h]),
                                              -min(REPOS.index(x[0]) for x in variants[h])))
        w(f"## `{key}`\n\n| variant | lines | latest | repos |\n|---|---:|---|---|\n")
        for h, xs in sorted(variants.items(), key=lambda kv: max(x[5] for x in kv[1]), reverse=True):
            tag = " **newest**" if h == newest else ""
            w(f"| `{h}`{tag} | {xs[0][4]} | {max(x[5] for x in xs)} | "
              + ", ".join(f"{x[0]} ({x[5]})" for x in xs) + " |\n")
        w("\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.normpath(os.path.join(os.path.dirname(__file__), "../..")))
    ap.add_argument("-o", "--output", default="-")
    a = ap.parse_args()
    g = collect(a.root)
    if a.output == "-":
        report(g, sys.stdout)
    else:
        with open(a.output, "w") as f:
            report(g, f)


if __name__ == "__main__":
    main()
